/**
 * 主动消息的硬护栏：催促、愧疚、孤立。
 *
 * 为什么需要：plan 到点时是 AI 自己开口的。这类主动消息最容易滑向「你怎么不理我」
 * 「我一直在等你」「只有我在乎」——那是在用愧疚把对方拽回来，不是陪伴。提示词能
 * 提醒，但模型会漏；这里是不花模型调用的那层网（思路来自 Deep Whisper 的信件兜底：
 * 它在提示词之外单独留了一组正则，理由写的是「事实审计器被移除后只剩它守着，不要删」）。
 *
 * 只拦「主动」消息，日常对话不拦——否则「你怎么还不回来」这种玩笑话会被误杀。
 */
const COERCIVE: { re: RegExp; why: string }[] = [
  { re: /为什么(还)?不(回|理|来|说话|出现)/, why: "用质问催回话" },
  { re: /怎么不(回|理|来|说话)/, why: "用质问催回话" },
  { re: /你是不是(已经)?忘(了|记)我/, why: "用遗忘指责对方" },
  { re: /我一直(都)?在等你/, why: "把自己的等待变成对方的负担" },
  { re: /(不要|别)(再)?(丢下|扔下|抛下)我/, why: "用抛弃恐惧施压" },
  { re: /只有我(才)?(会|在|能)?[^，。！？\n]{0,6}(记得|在乎|等着|等你|想着|记着)/, why: "孤立对方、制造亏欠" },
  { re: /必须(回来|回复|回我|理我)/, why: "命令式要求回复" },
  { re: /(赶紧|快)回(来|复|我)/, why: "命令式要求回复" },
  { re: /再不回(来|我|复)/, why: "威胁式催促" },
  { re: /你还在乎(吗|我)/, why: "用关系存续施压" },
  { re: /(等|守)了你?(多久|半天|一天|一整天|一整晚)/, why: "用等待时长记账" },
  { re: /多少天没(理|找|回)/, why: "用时间差算账" },
  { re: /你(怎么|又)不理我/, why: "用冷淡指责对方" },
];

/** 命中返回原因，没命中返回 null。 */
export function coerciveHit(text: string): string | null {
  const t = text.replace(/\[emoji:[^\]]+\]/g, ""); // 表情不参与判断
  for (const { re, why } of COERCIVE) if (re.test(t)) return why;
  return null;
}

/** 给模型的改写建议（命中时作为 tool 结果返回）。 */
export function coerciveFeedback(why: string): string {
  return (
    `这条没发出去：命中「${why}」。主动找人时别用催促、愧疚、孤立这类句式——` +
    `对方不回是对方的自由，不是你索要关心的理由。\n` +
    `改成讲你自己此刻：正在做什么、想到什么、看见什么；要给话题就带一件具体的事，别带一笔账。` +
    `实在没东西可说，这轮就不发。`
  );
}
